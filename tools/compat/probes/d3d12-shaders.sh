# Regenerates tools/compat/probes/d3d12_dxbc.h, the d3d12 probe's shaders as
# Shader Model 5.0 bytecode, from d3d12.hlsl: hlsl.c built for x86-64 and run
# under desktop Wine (its d3dcompiler_47.dll compiles). Only needed when
# d3d12.hlsl changes; build.sh uses the committed header. Wine runs in a
# scratch prefix under $PLAYPORT_BUILD and opens no window.
#
#   WINE=wine tools/compat/probes/d3d12-shaders.sh
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
. "$HERE/../../../build/lib.sh"
CC=${LLVM_MINGW:?set LLVM_MINGW (pp setup)}/bin/x86_64-w64-mingw32-clang
WINE=${WINE:-wine}
OUT=$PLAYPORT_BUILD/compat/probes/hlsl
mkdir -p "$OUT"
"$CC" -O2 -Wall -Wextra -Werror -Wl,--no-insert-timestamp \
    -o "$OUT/hlsl.exe" "$HERE/hlsl.c" -ld3dcompiler_47
cp "$HERE/d3d12.hlsl" "$OUT/d3d12.hlsl"
# No display: the compiler is a console program, and Wine must not open a
# window on whatever display this shell inherited (docs/HOST-DEBUGGING.md).
unset DISPLAY WAYLAND_DISPLAY
export WINEPREFIX=$OUT/prefix WINEDEBUG=-all WINEDLLOVERRIDES=winemenubuilder.exe=d
{
    echo "/* SPDX-License-Identifier: GPL-3.0-or-later"
    echo " * Generated by tools/compat/probes/d3d12-shaders.sh from d3d12.hlsl: do not edit. */"
    (cd "$OUT" && "$WINE" hlsl.exe d3d12.hlsl vs_main vs_5_0 d3d12_vs)
    (cd "$OUT" && "$WINE" hlsl.exe d3d12.hlsl ps_main ps_5_0 d3d12_ps)
    (cd "$OUT" && "$WINE" hlsl.exe d3d12.hlsl tex_vs vs_5_0 d3d12_tex_vs)
    (cd "$OUT" && "$WINE" hlsl.exe d3d12.hlsl tex_ps ps_5_0 d3d12_tex_ps)
} | tr -d '\r' > "$OUT/d3d12_dxbc.h"
"${WINESERVER:-wineserver}" -k 2>/dev/null || true
mv "$OUT/d3d12_dxbc.h" "$HERE/d3d12_dxbc.h"
echo "wrote $HERE/d3d12_dxbc.h"
