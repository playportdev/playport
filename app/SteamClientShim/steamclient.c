static void user_CancelAuthTicket(iface *self, uint32_t handle)
{
    static pp_sc_call c;
    (void)self;
    AcquireSRWLockExclusive(&lock);
    for (int i = 0; i < MAX_PENDING; i++) if (tickets[i].handle == handle) tickets[i].handle = 0;
    if (unix_call && handle) {
        memset(&c, 0, sizeof(c));
        c.magic = PP_SC_MAGIC;
        c.size = sizeof(c);
        c.method = PP_SC_TICKET_CANCEL;
        c.handle = handle;
        unix_call(unix_handle, PP_SC_CALL, &c);
    }
    ReleaseSRWLockExclusive(&lock);
}
/* EUserHasLicenseForAppResult: 0 has it, 1 does not, 2 no auth (the user is not this one). */
