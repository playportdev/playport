static uint32_t ticket(int web, const char *identity, void *buf, int cap, uint32_t *size)
{
    pp_sc_call *c;
    static pp_sc_call block;
    uint32_t handle = 0;
    if (size) *size = 0;
    if (!unix_call || !snapshot.armed) return 0;
    c = &block;
    memset(c, 0, sizeof(*c));
    c->magic = PP_SC_MAGIC;
    c->size = sizeof(*c);
    c->method = web ? PP_SC_TICKET_WEB_API : PP_SC_TICKET_SESSION;
    for (size_t i = 0; identity && identity[i] && i < sizeof(c->identity) - 1; i++) c->identity[i] = identity[i];
    if (unix_call(unix_handle, PP_SC_CALL, c) != PP_SC_OK || !c->handle) {
        say(web ? "web API ticket" : "auth session ticket", ": refused by the host", NULL, NULL, NULL, NULL);
        return 0;
    }
    if (!web && (!buf || cap < 0 || c->data_size > (uint32_t)cap)) {
        c->method = PP_SC_TICKET_CANCEL;
        unix_call(unix_handle, PP_SC_CALL, c);
        return 0;
    }
    for (int i = 0; i < MAX_PENDING; i++)
        if (!tickets[i].handle) {
            tickets[i].handle = c->handle;
            tickets[i].web = web;
            tickets[i].size = c->data_size;
            memcpy(tickets[i].bytes, c->data, c->data_size);
            break;
        }
    if (!web) {
        memcpy(buf, c->data, c->data_size);
        if (size) *size = c->data_size;
    }
    handle = c->handle;
    memset(c->data, 0, sizeof(c->data));
    return handle;
}
