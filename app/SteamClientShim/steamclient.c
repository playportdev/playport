// steamclient64.dll: Playport's Steam client for a game's (and its launcher's)
// genuine steam_api64.dll, for the launched app only (decision 0115).
//
// A genuine steam_api finds it through HKCU\Software\Valve\Steam\ActiveProcess
// (SteamClientDll64; the session root's pid stands for Steam's process), loads it
// and asks CreateInterface for an ISteamClient, then the client for the other
// interfaces by version string. Each interface version is a C object whose first
// field is its MSVC x64 vtable; the slot order comes from the public SDK headers
// (steamclient_slots.h, generated by build/steamclient-vtables.py). A method the
// shim implements answers from the host's snapshot or the play's ticket broker,
// through one unix call table (steam_client_protocol.h, WineHost steam_client.c);
// every other slot is a trampoline that answers 0 (false, none, not logged on)
// and logs its interface, version, slot and method name the first time. A
// version the table lacks gets an object of such trampolines, named by its
// version and logged; a name that is no Steam interface gets NULL.
//
// Callbacks and call results (auth ticket answers, the encrypted app ticket) are
// made here and handed out through Steam_BGetCallback and Steam_GetAPICallResult,
// as Steam's client hands them to steam_api.
//
// x86-64 only, freestanding: kernel32 alone, no C runtime (built by
// build/stages/steamclient.sh); ntdll's unix-call entry points are looked up.

#include <windows.h>
