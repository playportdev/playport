static uint64_t user_RequestEncryptedAppTicket(iface *self, void *data, int size)
{
    static pp_sc_call c;
    uint64_t call;
    (void)self; (void)data; (void)size;   /* the game's data is not sent (decision 0115) */
    AcquireSRWLockExclusive(&lock);
    app_ticket_size = 0;
    if (unix_call && snapshot.armed) {
        memset(&c, 0, sizeof(c));
        c.magic = PP_SC_MAGIC;
        c.size = sizeof(c);
        c.method = PP_SC_APP_TICKET;
        if (unix_call(unix_handle, PP_SC_CALL, &c) == PP_SC_OK && c.data_size <= sizeof(app_ticket)) {
            memcpy(app_ticket, c.data, c.data_size);
            app_ticket_size = c.data_size;
        }
        memset(c.data, 0, sizeof(c.data));
    }
    call = result_now(CB_ENCRYPTED_APP_TICKET, app_ticket_size ? ER_OK : ER_NO_CONNECTION);
    ReleaseSRWLockExclusive(&lock);
    say("encrypted app ticket: ", app_ticket_size ? "the Play's ticket" : "none", NULL, NULL, NULL, NULL);
    return call;
}
static uint8_t user_GetEncryptedAppTicket(iface *self, void *buf, int cap, uint32_t *size)
{
    uint8_t ok = 0;
    (void)self;
    AcquireSRWLockExclusive(&lock);
    if (size) *size = app_ticket_size;
    if (app_ticket_size && buf && cap >= 0 && app_ticket_size <= (uint32_t)cap) {
        memcpy(buf, app_ticket, app_ticket_size);
        ok = 1;
    }
    ReleaseSRWLockExclusive(&lock);
    return ok;
}

