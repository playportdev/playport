"""Generate the prefix registry seed from the staged builtin DLLs.

A Wine prefix normally gets its COM classes (and the rest of each builtin's
registration) from `wineboot`, which runs setupapi's register_fake_dll over
every builtin: each DLL carries its registration as WINE_REGISTRY resources
(ATL registrar scripts generated by widl), applied with the replacements
%MODULE% = C:\\windows\\system32\\<dll> and %SystemRoot% = C:\\windows.
The app never runs wineboot (one process, no services), so its prefix had no
Classes\\CLSID keys at all and CoCreateInstance(CLSID_MMDeviceEnumerator)
failed with REGDB_E_CLASSNOTREG on the device.

This script does the same registration at build time: it reads every
WINE_REGISTRY script in the staged arm64ec-windows set (the DLLs x86-64
guests load), interprets it with the rules of Wine's registrar
(dlls/atl/registrar.c do_process_key), and writes the resulting keys in
wineserver's registry file format:

  app/registry/system.reg   HKLM and HKCR keys (relative to \\Machine)
  app/registry/user.reg     HKCU keys (relative to the user key)

It adds the registrations some DllRegisterServer entry points write at run time
instead of carrying them as scripts: the Media Foundation transforms (MFTS) and
the Windows Imaging Component's codecs and pixel formats (register_wic, read
from windowscodecs' regsvr.c in the build's Wine tree), and wintrust's and msisip's
Authenticode registration (register_wintrust, register_msisip). Every key goes into the
64-bit view; i386 callers read the classes through Wine's shared
Software\\Classes\\Wow6432Node (decision 0072).

Both also carry the user profile keys wineboot and shell32 would otherwise
write (PROFILE below): the ProfileList, the user shell folders and the
Volatile Environment that gives a guest %USERPROFILE%, %APPDATA% and
%LOCALAPPDATA%. wine_host.c creates the directories they name.

wine_host.c appends every section a prefix's system.reg / user.reg does not
have yet, before the wineserver loads them, on every launch. So a fresh
install, an existing prefix and an app update that ships more DLLs all end up
registered, and nothing the prefix already holds is overwritten. A PROFILE
section is preceded by the MARKER comment line: for a marked key the prefix
already has, the values it lacks are added too (ntdll and shell32 create those
keys empty); any other key the prefix has is left alone.

Usage:
  prefix-registry.py            regenerate from app/Sources/S1Probe/Runtime/arm64ec-windows
  prefix-registry.py --check    fail if the committed files differ from a regeneration
Run it after build/stages/stage-artifacts.py stage (the staged DLLs are hash-checked there).
"""

